-- Loan files as received, with full identifiers (masked only at the API/log boundary).
CREATE TABLE loan_file (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id            VARCHAR(64)    NOT NULL,
    payload_hash       VARCHAR(64)    NOT NULL,
    payload            TEXT           NOT NULL,
    applicant_name     VARCHAR(200)   NOT NULL,
    pan                VARCHAR(10)    NOT NULL,
    account_number     VARCHAR(34)    NOT NULL,
    submitted_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    score              INT            NOT NULL,
    band               VARCHAR(10)    NOT NULL,
    degraded_signals   VARCHAR(200),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_loan_file_file_id UNIQUE (file_id)
);

CREATE TABLE rule_hit (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_file_id  BIGINT        NOT NULL REFERENCES loan_file (id),
    rule_id       VARCHAR(40)   NOT NULL,
    points        INT           NOT NULL,
    reason        VARCHAR(1000) NOT NULL,
    evidence      TEXT          NOT NULL
);
CREATE INDEX idx_rule_hit_loan_file ON rule_hit (loan_file_id);

CREATE TABLE fcu_case (
    case_id       VARCHAR(36)  PRIMARY KEY,
    loan_file_id  BIGINT       NOT NULL REFERENCES loan_file (id),
    file_id       VARCHAR(64)  NOT NULL,
    score         INT          NOT NULL,
    band          VARCHAR(10)  NOT NULL,
    status        VARCHAR(30)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_fcu_case_loan_file UNIQUE (loan_file_id)
);
-- Supports GET /api/cases?status=... ordered by score (highest first).
CREATE INDEX idx_fcu_case_status_score ON fcu_case (status, score DESC, created_at);
