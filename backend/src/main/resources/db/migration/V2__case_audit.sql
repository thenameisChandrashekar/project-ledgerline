-- Append-only history of case dispositions. The application has no update or delete path for these rows.
CREATE TABLE case_audit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id      VARCHAR(36)   NOT NULL REFERENCES fcu_case (case_id),
    from_status  VARCHAR(30)   NOT NULL,
    to_status    VARCHAR(30)   NOT NULL,
    actor        VARCHAR(100)  NOT NULL,
    comment      VARCHAR(2000) NOT NULL,
    acted_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_case_audit_case ON case_audit (case_id, acted_at);
